//! Writes `src/types.rs` from the Debug Adapter Protocol's JSON schema (`schema/debugAdapterProtocol.json`). A dev
//! tool, run by hand when the schema is updated; its output is committed:
//!
//!     cargo run -p vor --example gen_types -- runtime/crates/vor/schema/debugAdapterProtocol.json \
//!       > runtime/crates/vor/src/types.rs && cargo fmt -p vor
//!
//! Every object becomes a struct whose unknown fields are kept (`extra`, flattened), so an adapter's own fields pass
//! through. Named string enums stay `String` (an adapter may send a value the schema lacks), with their values as
//! constants. Requests and events become marker types implementing [`crate::Request`] / [`crate::Event`].
use serde_json::{Map, Value};
use std::collections::BTreeMap;
use std::fmt::Write;

struct Gen {
    defs: Map<String, Value>,
    out: String,
    /// Struct definitions still to write (inline bodies), by name.
    pending: BTreeMap<String, Value>,
}

fn main() {
    let path = std::env::args()
        .nth(1)
        .expect("usage: gen_types SCHEMA.json");
    let schema: Value = serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
    let defs = schema["definitions"].as_object().unwrap().clone();
    let mut g = Gen {
        defs,
        out: String::new(),
        pending: BTreeMap::new(),
    };
    g.out.push_str(
        "// @generated by `cargo run -p vor --example gen_types` from schema/debugAdapterProtocol.json (MIT,\n\
         // Microsoft; see schema/README.md). Do not edit by hand.\n\
         //! The Debug Adapter Protocol's types, generated from its JSON schema.\n\
         #![allow(clippy::doc_markdown, clippy::large_enum_variant, missing_docs)]\n\
         use serde::{Deserialize, Serialize};\n\
         use serde_json::{Map, Value};\n\n",
    );
    let names: Vec<String> = g.defs.keys().cloned().collect();
    let mut requests = Vec::new();
    let mut events = Vec::new();
    for name in &names {
        let def = g.defs[name].clone();
        if let Some(all) = def.get("allOf").and_then(Value::as_array) {
            let base = all[0]["$ref"]
                .as_str()
                .unwrap_or("")
                .rsplit('/')
                .next()
                .unwrap_or("");
            let part = &all[1];
            match base {
                "ProtocolMessage" => {}
                "Request" => {
                    let cmd = part["properties"]["command"]["enum"][0]
                        .as_str()
                        .unwrap()
                        .to_owned();
                    let args = part["properties"]
                        .get("arguments")
                        .and_then(|a| a.get("$ref"))
                        .and_then(Value::as_str)
                        .map(|r| r.rsplit('/').next().unwrap().to_owned());
                    requests.push((name.trim_end_matches("Request").to_owned(), cmd, args));
                }
                "Response" => {
                    if let Some(body) = part["properties"].get("body") {
                        let body_name = format!("{}Body", name);
                        g.pending.insert(body_name, body.clone());
                    }
                }
                "Event" => {
                    let ev = part["properties"]["event"]["enum"][0]
                        .as_str()
                        .unwrap()
                        .to_owned();
                    let has_body = part["properties"].get("body").is_some();
                    let ename = name.trim_end_matches("Event").to_owned();
                    if let Some(body) = part["properties"].get("body") {
                        g.pending.insert(format!("{ename}EventBody"), body.clone());
                    }
                    events.push((ename, ev, has_body));
                }
                other => {
                    // a struct extending another: the base's fields flattened in
                    let mut merged = part.clone();
                    merged["x-base"] = Value::String(other.to_owned());
                    g.pending.insert(name.clone(), merged);
                }
            }
        } else if def.get("type").and_then(Value::as_str) == Some("string") {
            g.string_type(name, &def);
        } else {
            g.pending.insert(name.clone(), def);
        }
    }
    while let Some((name, def)) = g.pending.pop_first() {
        g.object(&name, &def);
    }
    g.out.push_str("/// Every request: its command and its arguments' and answer's types.\npub mod requests {\n    use super::*;\n");
    for (name, cmd, args) in &requests {
        let resp = format!("{name}Response");
        let body = if g.has_body(&resp) {
            format!("{resp}Body")
        } else {
            "Value".to_owned()
        };
        let args = args.clone().unwrap_or_else(|| "Value".to_owned());
        writeln!(
            g.out,
            "    /// `{cmd}`.\n    #[derive(Debug, Clone, Copy)]\n    pub struct {name};\n    impl crate::Request for {name} {{\n        const COMMAND: &'static str = {cmd:?};\n        type Arguments = {args};\n        type Body = {body};\n    }}"
        )
        .unwrap();
    }
    g.out.push_str("}\n\n/// Every event: its name and its body's type.\npub mod events {\n    use super::*;\n");
    for (name, ev, has_body) in &events {
        let body = if *has_body {
            format!("{name}EventBody")
        } else {
            "Value".to_owned()
        };
        writeln!(
            g.out,
            "    /// `{ev}`.\n    #[derive(Debug, Clone, Copy)]\n    pub struct {name};\n    impl crate::Event for {name} {{\n        const EVENT: &'static str = {ev:?};\n        type Body = {body};\n    }}"
        )
        .unwrap();
    }
    g.out.push_str("}\n");
    print!("{}", g.out);
}

impl Gen {
    fn has_body(&self, resp: &str) -> bool {
        self.defs
            .get(resp)
            .and_then(|d| d.get("allOf"))
            .and_then(|a| a[1]["properties"].get("body"))
            .is_some()
    }

    fn doc(&mut self, indent: &str, v: &Value) {
        if let Some(d) = v.get("description").and_then(Value::as_str) {
            for line in d.lines() {
                let line = line.replace("[", "\\[").replace("]", "\\]");
                writeln!(self.out, "{indent}/// {}", line.trim_end()).unwrap();
            }
        }
    }

    fn string_type(&mut self, name: &str, def: &Value) {
        self.doc("", def);
        writeln!(self.out, "pub type {name} = String;").unwrap();
        let vals = def
            .get("enum")
            .or_else(|| def.get("_enum"))
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        if !vals.is_empty() {
            writeln!(self.out, "/// The values of [`{name}`] the schema names.\n#[allow(non_snake_case)]\npub mod {name}Values {{").unwrap();
            for v in vals {
                let s = v.as_str().unwrap();
                writeln!(self.out, "    pub const {}: &str = {s:?};", konst(s)).unwrap();
            }
            self.out.push_str("}\n");
        }
        self.out.push('\n');
    }

    fn object(&mut self, name: &str, def: &Value) {
        self.doc("", def);
        self.out
            .push_str("#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]\n");
        writeln!(self.out, "pub struct {name} {{").unwrap();
        if let Some(base) = def.get("x-base").and_then(Value::as_str) {
            writeln!(self.out, "    #[serde(flatten)]\n    pub base: {base},").unwrap();
        }
        let required: Vec<&str> = def
            .get("required")
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let props = def
            .get("properties")
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_default();
        for (pname, p) in &props {
            let ty = self.ty(name, pname, p);
            self.doc("    ", p);
            let field = field_name(pname);
            if field != *pname {
                writeln!(self.out, "    #[serde(rename = {pname:?})]").unwrap();
            }
            if required.contains(&pname.as_str()) {
                writeln!(self.out, "    pub {field}: {ty},").unwrap();
            } else {
                writeln!(
                    self.out,
                    "    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n    pub {field}: Option<{ty}>,"
                )
                .unwrap();
            }
        }
        self.out.push_str(
            "    /// Fields the schema does not name (an adapter's own), kept as they came.\n    #[serde(flatten)]\n    pub extra: Map<String, Value>,\n}\n\n",
        );
    }

    fn ty(&mut self, owner: &str, pname: &str, p: &Value) -> String {
        if let Some(r) = p.get("$ref").and_then(Value::as_str) {
            return r.rsplit('/').next().unwrap().to_owned();
        }
        match p.get("type") {
            Some(Value::String(t)) => match t.as_str() {
                "string" => "String".into(),
                "integer" => "i64".into(),
                "number" => "f64".into(),
                "boolean" => "bool".into(),
                "array" => format!("Vec<{}>", self.ty(owner, pname, &p["items"])),
                "object" => {
                    if p.get("properties").is_some() {
                        let n = format!("{owner}{}", camel(pname));
                        self.pending.insert(n.clone(), p.clone());
                        n
                    } else if let Some(ap) = p.get("additionalProperties") {
                        match ap.get("type") {
                            Some(Value::String(s)) if s == "string" => {
                                "std::collections::BTreeMap<String, String>".into()
                            }
                            Some(Value::Array(_)) => {
                                "std::collections::BTreeMap<String, Option<String>>".into()
                            }
                            _ => "Map<String, Value>".into(),
                        }
                    } else {
                        "Map<String, Value>".into()
                    }
                }
                _ => "Value".into(),
            },
            _ => "Value".into(),
        }
    }
}

fn camel(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().chain(c).collect(),
        None => String::new(),
    }
}

fn field_name(s: &str) -> String {
    // camelCase to snake_case, an acronym kept as one word (supportsANSIStyling: supports_ansi_styling)
    let c: Vec<char> = s.trim_start_matches('_').chars().collect();
    let mut out = String::new();
    for (i, &ch) in c.iter().enumerate() {
        if ch.is_uppercase() {
            let prev_lower = i > 0 && (c[i - 1].is_lowercase() || c[i - 1].is_ascii_digit());
            let acronym_end =
                i > 0 && c[i - 1].is_uppercase() && c.get(i + 1).is_some_and(|n| n.is_lowercase());
            if prev_lower || acronym_end {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    match out.as_str() {
        "type" => "type_".into(),
        "ref" => "ref_".into(),
        "mod" => "mod_".into(),
        _ => out,
    }
}

fn konst(s: &str) -> String {
    let mut out = String::new();
    for ch in s.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_uppercase());
        } else {
            out.push('_');
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}
