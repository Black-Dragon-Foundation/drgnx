//! Views: the record files written back from graph data.  A [`ViewModel`] is a file's pieces in order (the `body`
//! of each entity [`crate::import::ops`] made); rendering is their concatenation, so an unchanged graph renders
//! the imported file byte for byte.  The written file carries a one-line header comment ([`header`]) that the
//! importer strips ([`strip_header`]).

/// A view's pieces, in `seq` order.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct ViewModel {
    pub parts: Vec<String>,
    /// Per part (the same length as `parts`, or empty when only rendering): the entity id, kind and role.
    pub ids: Vec<String>,
    pub kinds: Vec<String>,
    pub roles: Vec<String>,
    /// The graph version the model was read at (a proposal records it).
    pub version: u64,
}

pub fn render(model: &ViewModel) -> String {
    model.parts.concat()
}

const MD: &str = "<!-- generated by drgnx from the graph; edits are read back as proposals -->\n";
const ORG: &str = "# generated by drgnx from the graph; edits are read back as proposals\n";

/// The header comment of the view at PATH (Org comment for `.org`, an HTML comment otherwise).
pub fn header(path: &std::path::Path) -> &'static str {
    if path.extension().is_some_and(|e| e == "org") {
        ORG
    } else {
        MD
    }
}

/// TEXT without a leading view header.
pub fn strip_header(text: &str) -> &str {
    for h in [MD, ORG] {
        if let Some(rest) = text.strip_prefix(h) {
            return rest;
        }
    }
    text
}

/// The file at PATH as written: header, then the rendered pieces.
pub fn file_text(path: &std::path::Path, model: &ViewModel) -> String {
    format!("{}{}", header(path), render(model))
}

/// A stable digest of TEXT (FNV-1a, 64 bit, 16 hex digits): what the hub compares a view file against.
pub fn digest(text: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in text.bytes() {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{h:016x}")
}
