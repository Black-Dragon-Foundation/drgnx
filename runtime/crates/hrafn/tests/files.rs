#[test]
fn include_exclude_globs_narrow_the_list() {
    let d = repo(&[
        ("a.el", "a\n"),
        ("sub/b.el", "b\n"),
        ("sub/deep/c.el", "c\n"),
        ("notes.md", "n\n"),
        ("vendor/v.el", "v\n"),
        ("README", "r\n"),
    ]);
    let cfg = |inc: &[&str], exc: &[&str]| Config {
        include: inc.iter().map(|s| s.to_string()).collect(),
        exclude: exc.iter().map(|s| s.to_string()).collect(),
        off: false,
    };
    let p = |c: Config| {
        paths(&run(d.path(), &c).unwrap())
            .iter()
            .map(|s| s.to_string())
            .collect::<Vec<_>>()
    };
    // no slash: any depth
    assert_eq!(
        p(cfg(&["*.el"], &[])),
        ["a.el", "sub/b.el", "sub/deep/c.el", "vendor/v.el"]
    );
    // a trailing slash: everything below
    assert_eq!(
        p(cfg(&["*.el"], &["vendor/"])),
        ["a.el", "sub/b.el", "sub/deep/c.el"]
    );
    // `*` stays in a component, `**/` crosses directories
    assert_eq!(p(cfg(&["sub/*.el"], &[])), ["sub/b.el"]);
    assert_eq!(p(cfg(&["sub/**/*.el"], &[])), ["sub/b.el", "sub/deep/c.el"]);
    assert_eq!(p(cfg(&["sub/**"], &["**/deep/**"])), ["sub/b.el"]);
    assert_eq!(p(cfg(&[], &["*.el", "*.md"])), ["README"]);
    // it only narrows: a dot file stays out whatever is included
    let d2 = repo(&[(".x.el", "x\n"), ("y.el", "y\n")]);
    assert_eq!(
        paths(&run(d2.path(), &cfg(&["*.el"], &[])).unwrap()),
        ["y.el"]
    );
}

