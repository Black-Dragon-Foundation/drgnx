use hrafn::{Class, Config, CoverageError, GitCli, Lang, Listed, coverage, list};
use std::collections::HashMap;
use std::path::Path;
use std::process::Command;

fn git(dir: &Path, args: &[&str]) {
    let st = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(args)
        .status()
        .unwrap();
    assert!(st.success(), "git {args:?}");
}

/// A repository in a temp dir, built from a manifest of (path, content); everything is added to the index. The temp dir
/// is under the real path of the system's: `list` refuses a root with a link in its path, as the hub never gives it one
/// (it canonicalizes the root first), and macOS's temp dir is under /var, a link to /private/var.
fn repo(manifest: &[(&str, &str)]) -> tempfile::TempDir {
    let dir = tempfile::tempdir_in(std::env::temp_dir().canonicalize().unwrap()).unwrap();
    git(dir.path(), &["init", "-q"]);
    for (p, c) in manifest {
        let f = dir.path().join(p);
        std::fs::create_dir_all(f.parent().unwrap()).unwrap();
        std::fs::write(f, c).unwrap();
    }
    git(dir.path(), &["add", "-A"]);
    dir
}

fn all(_: &str) -> bool {
    true
}

fn paths(l: &[Listed]) -> Vec<&str> {
    l.iter().map(|x| x.path.as_str()).collect()
}

fn run(dir: &Path, cfg: &Config) -> std::io::Result<Vec<Listed>> {
    list(dir, &GitCli, cfg, &all)
}

#[test]
fn lists_el_and_shebang_script() {
    let d = repo(&[
        ("core/a.el", "(defun a ())\n"),
        ("bin/tool", "#!/usr/bin/env bash\necho hi\n"),
        ("LICENSE", "text\n"),
        ("src/lib.rs", "fn f() {}\n"),
        (".hidden/x.el", "x\n"),
        (".env", "K=v\n"),
        ("keys/server.pem", "k\n"),
        ("app/secrets.txt", "s\n"),
        ("blob.bin", "a\0b"),
    ]);
    let l = run(d.path(), &Config::default()).unwrap();
    assert_eq!(
        paths(&l),
        ["LICENSE", "bin/tool", "core/a.el", "src/lib.rs"]
    );
    let by = |p: &str| l.iter().find(|x| x.path == p).unwrap();
    assert_eq!(by("bin/tool").lang, Lang::Shell);
    assert_eq!(by("core/a.el").lang, Lang::Elisp);
    assert_eq!(by("src/lib.rs").lang, Lang::Rust);
    assert_eq!(by("LICENSE").lang, Lang::Text);
    assert_eq!(by("core/a.el").blob.len(), 40);
}

#[test]
fn nested_repo_left_out() {
    let d = repo(&[("a.el", "a\n")]);
    let inner = d.path().join("vendor/inner");
    std::fs::create_dir_all(&inner).unwrap();
    git(&inner, &["init", "-q"]);
    std::fs::write(inner.join("b.el"), "b\n").unwrap();
    let l = run(d.path(), &Config::default()).unwrap();
    assert_eq!(paths(&l), ["a.el"]);
}

#[test]
fn generated_marked_not_dropped() {
    let d = repo(&[
        ("a.el", "(defun a ())\n"),
        ("x-autoloads.el", "(x)\n"),
        ("Cargo.lock", "lock\n"),
        ("b.el", ";; Generated by tool\n(b)\n"),
        ("c.el", ";; DO NOT EDIT\n(c)\n"),
        ("d.el", "(d)\n"),
        (
            ".gitattributes",
            "d.el linguist-generated\nvend/* linguist-vendored\n",
        ),
        ("vend/v.el", "(v)\n"),
        ("app.min.js", "x\n"),
    ]);
    let l = run(d.path(), &Config::default()).unwrap();
    let marks: Vec<(&str, bool)> = l.iter().map(|x| (x.path.as_str(), x.generated)).collect();
    assert_eq!(
        marks,
        [
            ("Cargo.lock", true),
            ("a.el", false),
            ("app.min.js", true),
            ("b.el", true),
            ("c.el", true),
            ("d.el", true),
            ("vend/v.el", true),
            ("x-autoloads.el", true),
        ]
    );
}

#[test]
fn denied_path_never_listed() {
    let d = repo(&[("a.el", "a\n"), ("private/b.el", "b\n")]);
    let l = list(d.path(), &GitCli, &Config::default(), &|p: &str| {
        !p.starts_with("private/")
    })
    .unwrap();
    assert_eq!(paths(&l), ["a.el"]);
}

#[test]
fn include_exclude_globs_narrow_the_list() {
    let d = repo(&[
        ("a.el", "a\n"),
        ("sub/b.el", "b\n"),
        ("sub/deep/c.el", "c\n"),
        ("notes.md", "n\n"),
        ("vendor/v.el", "v\n"),
        ("README", "r\n"),
    ]);
    let cfg = |inc: &[&str], exc: &[&str]| Config {
        include: inc.iter().map(|s| s.to_string()).collect(),
        exclude: exc.iter().map(|s| s.to_string()).collect(),
        off: false,
    };
    let p = |c: Config| {
        paths(&run(d.path(), &c).unwrap())
            .iter()
            .map(|s| s.to_string())
            .collect::<Vec<_>>()
    };
    // no slash: any depth
    assert_eq!(
        p(cfg(&["*.el"], &[])),
        ["a.el", "sub/b.el", "sub/deep/c.el", "vendor/v.el"]
    );
    // a trailing slash: everything below
    assert_eq!(
        p(cfg(&["*.el"], &["vendor/"])),
        ["a.el", "sub/b.el", "sub/deep/c.el"]
    );
    // `*` stays in a component, `**/` crosses directories
    assert_eq!(p(cfg(&["sub/*.el"], &[])), ["sub/b.el"]);
    assert_eq!(p(cfg(&["sub/**/*.el"], &[])), ["sub/b.el", "sub/deep/c.el"]);
    assert_eq!(p(cfg(&["sub/**"], &["**/deep/**"])), ["sub/b.el"]);
    assert_eq!(p(cfg(&[], &["*.el", "*.md"])), ["README"]);
    // it only narrows: a dot file stays out whatever is included
    let d2 = repo(&[(".x.el", "x\n"), ("y.el", "y\n")]);
    assert_eq!(
        paths(&run(d2.path(), &cfg(&["*.el"], &[])).unwrap()),
        ["y.el"]
    );
}

#[test]
fn off_lists_nothing() {
    let d = repo(&[("a.el", "a\n")]);
    let cfg = Config {
        off: true,
        ..Config::default()
    };
    assert!(run(d.path(), &cfg).unwrap().is_empty());
}

#[test]
fn unreadable_search_eld_stops_the_listing() {
    let d = repo(&[("a.el", "a\n")]);
    // a directory where the file should be
    std::fs::create_dir_all(d.path().join(".drgnx/search.eld")).unwrap();
    let e = run(d.path(), &Config::default()).unwrap_err();
    assert!(e.to_string().contains("search.eld cannot be read"), "{e}");
    // empty
    std::fs::remove_dir(d.path().join(".drgnx/search.eld")).unwrap();
    std::fs::write(d.path().join(".drgnx/search.eld"), "").unwrap();
    assert!(run(d.path(), &Config::default()).is_err());
    // readable: fine
    std::fs::write(d.path().join(".drgnx/search.eld"), "(:off nil)\n").unwrap();
    assert_eq!(paths(&run(d.path(), &Config::default()).unwrap()), ["a.el"]);
}

#[test]
fn fifo_and_symlink_never_listed() {
    let d = repo(&[("a.el", "a\n"), ("target.el", "t\n")]);
    std::os::unix::fs::symlink("target.el", d.path().join("link.el")).unwrap();
    let st = Command::new("mkfifo")
        .arg(d.path().join("pipe.el"))
        .status()
        .unwrap();
    assert!(st.success());
    let l = run(d.path(), &Config::default()).unwrap();
    assert_eq!(paths(&l), ["a.el", "target.el"]);
}

#[test]
fn uncommitted_edit_changes_blob() {
    let d = repo(&[("a.el", "one\n")]);
    git(
        d.path(),
        &[
            "-c",
            "user.name=t",
            "-c",
            "user.email=t@t",
            "commit",
            "-q",
            "-m",
            "m",
        ],
    );
    let before = run(d.path(), &Config::default()).unwrap()[0].blob.clone();
    std::fs::write(d.path().join("a.el"), "two\n").unwrap();
    let after = run(d.path(), &Config::default()).unwrap()[0].blob.clone();
    assert_ne!(before, after);
}

fn listed(path: &str, class: Class, size: u64) -> Listed {
    Listed {
        path: path.into(),
        blob: "b".into(),
        class,
        lang: Lang::Text,
        generated: false,
        size,
    }
}

#[test]
fn coverage_flags_class_with_no_chunks() {
    let l = vec![
        listed("a.el", Class::Code, 5),
        listed("t/x.el", Class::Test, 5),
    ];
    let c = HashMap::from([("a.el".to_string(), 2u32)]);
    let e = coverage(&l, &c);
    assert!(e.contains(&CoverageError::ClassWithNoChunks(Class::Test)));
    assert!(!e.contains(&CoverageError::ClassWithNoChunks(Class::Code)));
    // a class with no files is not an error
    assert!(!e.contains(&CoverageError::ClassWithNoChunks(Class::Docs)));
}

#[test]
fn coverage_flags_nonempty_file_without_chunks() {
    let l = vec![
        listed("a.el", Class::Code, 5),
        listed("b.el", Class::Code, 5),
        listed("empty.el", Class::Code, 0),
    ];
    let c = HashMap::from([("a.el".to_string(), 1u32)]);
    assert_eq!(
        coverage(&l, &c),
        vec![CoverageError::FileWithoutChunks("b.el".into())]
    );
}
