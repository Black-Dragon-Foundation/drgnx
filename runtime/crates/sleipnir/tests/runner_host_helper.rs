//! The job helper's runner-host rows: they run inside a fake runner (`test/runners/`), as the user `runner` with its
//! user manager and rootless podman, with the real `sleipnir` and `drgnx-key` beside them (`SLEIPNIR_TEST_BIN`), never
//! on a developer's machine:
//!
//! ```text
//! cargo test -p sleipnir --features test-hooks --test runner_host_helper --no-run
//! fleet.sh host <the test binary> [FILTER]      # --ignored, in every runner
//! ```
//!
//! The keyed rows (`relay_keys::`, `#[ignore = "keys"]`) need the relay's image and run on the Fedora VM gate instead
//! (their module says how).
//!
