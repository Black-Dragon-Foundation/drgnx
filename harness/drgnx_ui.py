#!/usr/bin/env python3
"""drgnx harness sessions: start, drive, capture and stop GUI Emacs under a headless compositor.

A session `drgnx-ui-N` is a transient systemd user unit running
dbus-run-session -> mutter --headless -> emacs (pgtk) with a generated init directory and its
own server socket inside the session's run directory. Nothing here talks to any other Emacs:
every call resolves its session from this harness's state directory. See docs/harness.md.
"""
import argparse, json, os, re, shutil, signal, subprocess, sys, time
from pathlib import Path

HARNESS = Path(__file__).resolve().parent
REPO = HARNESS.parent
KEEP_ENV = ("HOME", "USER", "LOGNAME", "LANG", "LC_ALL", "PATH", "XDG_RUNTIME_DIR", "GRYPHN_EMACS_DIR")
LINK = ("extras", "lisp", "site-lisp", "tree-sitter", "snippets", "themes")   # code: linked read-only
COPY = ("custom.el",)                                                        # may be written: copied

EARLY_INIT = """;;; early-init.el --- generated by drgnx for a harness session; do not edit -*- lexical-binding: t -*-
(load (expand-file-name "init/prelude.el" (getenv "DRGNX_UI_HARNESS")) nil t)
(drgnx-ui-load-config "early-init.el")
"""
INIT = """;;; init.el --- generated by drgnx for a harness session; do not edit -*- lexical-binding: t -*-
(drgnx-ui-load-config "init.el")
"""


class HarnessError(Exception):
    pass


def state_root():
    base = os.environ.get("DRGNX_UI_STATE")
    if not base:
        xdg = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
        base = os.path.join(xdg, "drgnx", "ui")
    return Path(base)


def emacs_bin():
    return os.environ.get("DRGNX_EMACS") or shutil.which("emacs-pgtk") or "emacs"


def resolve_config(config):
    """None for the minimal config, else the external config directory (must hold init.el)."""
    if config in (None, "", "minimal"):
        return None
    if config == "gryphn":
        d = Path(os.environ.get("DRGNX_GRYPHN_CONFIG") or "~/.config/emacs").expanduser()
    else:
        d = Path(config).expanduser()
    if not (d / "init.el").is_file():
        raise HarnessError(f"config {config!r}: no init.el in {d}")
    return d.resolve()


def prepare_run(name, config=None, size="1600x900", root=None):
    if not re.fullmatch(r"[0-9]+x[0-9]+", size or ""):
        raise HarnessError(f"size must be WxH, got {size!r}")
    cfg = resolve_config(config)
    root = Path(root) if root else state_root()
    root.mkdir(parents=True, exist_ok=True)
    run = root / name
    run.mkdir()                                   # FileExistsError: never reuse a run dir
    (run / "init").mkdir()
    (run / "out").mkdir()
    (run / "sock").mkdir()
    os.chmod(run / "sock", 0o700)                 # server-start refuses anything else
    (run / "init" / "early-init.el").write_text(EARLY_INIT)
    (run / "init" / "init.el").write_text(INIT)
    if cfg:
        for n in LINK:
            if (cfg / n).exists():
                (run / "init" / n).symlink_to(cfg / n)
        for n in COPY:
            if (cfg / n).is_file():
                shutil.copy2(cfg / n, run / "init" / n)
    sess = {"name": name, "run": str(run), "socket": str(run / "sock" / name), "size": size,
            "config": config or "minimal", "config_dir": str(cfg) if cfg else "", "created": time.time()}
    (run / "session.json").write_text(json.dumps(sess, indent=1))
    return sess


def session_env(sess, extra=None):
    env = {k: os.environ[k] for k in KEEP_ENV if k in os.environ}
    env.update(DRGNX_UI_NAME=sess["name"], DRGNX_UI_RUN=sess["run"], DRGNX_UI_HARNESS=str(HARNESS),
               DRGNX_UI_CONFIG=sess["config_dir"], EMACS_SOCKET_NAME=sess["socket"])
    env.update(extra or {})
    return env


def env_argv(env):
    return ["env", "-i", *[f"{k}={v}" for k, v in sorted(env.items())]]


def compositor_argv(sess):
    return ["dbus-run-session", "--", "mutter", "--headless", "--wayland", "--no-x11",
            "--wayland-display", sess["name"], "--virtual-monitor", sess["size"], "--",
            emacs_bin(), "--init-directory", str(Path(sess["run"]) / "init"), "--fullscreen"]


def run_ert_session(tests_dir, timeout=110):
    """Run the ERT suite in TESTS_DIR inside a foreground session. Returns (rc, results, run)."""
    name = f"drgnx-ui-test-{os.getpid()}-{int(time.time() * 1000) % 100000}"
    sess = prepare_run(name, None, "1600x900")
    run = Path(sess["run"])
    results = run / "results.json"
    env = session_env(sess, {"DRGNX_UI_TEST": str(Path(tests_dir).resolve()), "DRGNX_UI_RESULTS": str(results)})
    with open(run / "session.log", "w") as log:
        p = subprocess.Popen([*env_argv(env), *compositor_argv(sess)], stdout=log,
                             stderr=subprocess.STDOUT, start_new_session=True)
        try:
            rc = p.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)
            p.wait()
            rc = 124
    subprocess.run(["pkill", "-KILL", "-f", name], capture_output=True)  # belt and braces
    data = json.loads(results.read_text()) if results.is_file() else None
    return rc, data, run


def run_ui_tests():
    """`drgnx test --ui`: GUI ERT suite in a session, then live session tests. Returns exit code."""
    t0 = time.time()
    timeout = int(os.environ.get("DRGNX_UI_TEST_TIMEOUT", "110"))
    rc, results, run = run_ert_session(REPO / "test" / "ui", timeout)
    if results:
        print(f"ui ERT: {results['passed']}/{results['total']} passed")
        for f in results["failures"]:
            print(f"  FAIL {f['name']}: {f['condition']}")
    else:
        print(f"ui ERT: no results (exit {rc}); log kept in {run}")
    ok = rc == 0 and results is not None and results["failed"] == 0
    if ok:
        shutil.rmtree(run)
    live = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", str(REPO / "test" / "ui"),
                           "-p", "test_*.py"], env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})
    ok = ok and live.returncode == 0
    print(f"ui tier: {'green' if ok else 'RED'} in {time.time() - t0:.1f}s")
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(prog="drgnx ui")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("test-ui")
    a = ap.parse_args(argv)
    if a.cmd == "test-ui":
        return run_ui_tests()


if __name__ == "__main__":
    sys.exit(main())
