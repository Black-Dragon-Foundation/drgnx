#!/usr/bin/env python3
"""drgnx harness sessions: start, drive, capture and stop GUI Emacs under a headless compositor.

A session `drgnx-ui-N` is a transient systemd user unit running
dbus-run-session -> mutter --headless -> emacs (pgtk) with a generated init directory and its
own server socket inside the session's run directory. Nothing here talks to any other Emacs:
every call resolves its session from this harness's state directory. See docs/harness.md.
"""
import argparse, json, os, re, shutil, signal, subprocess, sys, tempfile, time
from pathlib import Path

HARNESS = Path(__file__).resolve().parent
REPO = HARNESS.parent
NAME_RE = re.compile(r"drgnx-ui-[0-9]+")
KEEP_ENV = ("HOME", "USER", "LOGNAME", "LANG", "LC_ALL", "PATH", "XDG_RUNTIME_DIR", "GRYPHN_EMACS_DIR")
LINK = ("extras", "lisp", "site-lisp", "tree-sitter", "snippets", "themes")   # code: linked read-only
COPY = ("custom.el",)                                                        # may be written: copied

EARLY_INIT = """;;; early-init.el --- generated by drgnx for a harness session; do not edit -*- lexical-binding: t -*-
(load (expand-file-name "init/prelude.el" (getenv "DRGNX_UI_HARNESS")) nil t)
(drgnx-ui-load-config "early-init.el")
"""
INIT = """;;; init.el --- generated by drgnx for a harness session; do not edit -*- lexical-binding: t -*-
(drgnx-ui-load-config "init.el")
"""


class HarnessError(Exception):
    pass


class Refused(HarnessError):
    pass


def state_root():
    base = os.environ.get("DRGNX_UI_STATE")
    if not base:
        xdg = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
        base = os.path.join(xdg, "drgnx", "ui")
    return Path(base)


def emacs_bin():
    return os.environ.get("DRGNX_EMACS") or shutil.which("emacs-pgtk") or "emacs"


def resolve_config(config):
    """None for the minimal config, else the external config directory (must hold init.el)."""
    if config in (None, "", "minimal"):
        return None
    if config == "gryphn":
        d = Path(os.environ.get("DRGNX_GRYPHN_CONFIG") or "~/.config/emacs").expanduser()
    else:
        d = Path(config).expanduser()
    if not (d / "init.el").is_file():
        raise HarnessError(f"config {config!r}: no init.el in {d}")
    return d.resolve()


def prepare_run(name, config=None, size="1600x900", root=None):
    if not re.fullmatch(r"[0-9]+x[0-9]+", size or ""):
        raise HarnessError(f"size must be WxH, got {size!r}")
    cfg = resolve_config(config)
    root = Path(root) if root else state_root()
    root.mkdir(parents=True, exist_ok=True)
    run = root / name
    run.mkdir()                                   # FileExistsError: never reuse a run dir
    (run / "init").mkdir()
    (run / "out").mkdir()
    (run / "sock").mkdir()
    os.chmod(run / "sock", 0o700)                 # server-start refuses anything else
    (run / "init" / "early-init.el").write_text(EARLY_INIT)
    (run / "init" / "init.el").write_text(INIT)
    if cfg:
        for n in LINK:
            if (cfg / n).exists():
                (run / "init" / n).symlink_to(cfg / n)
        for n in COPY:
            if (cfg / n).is_file():
                shutil.copy2(cfg / n, run / "init" / n)
    sess = {"name": name, "run": str(run), "socket": str(run / "sock" / name), "size": size,
            "config": config or "minimal", "config_dir": str(cfg) if cfg else "", "created": time.time()}
    (run / "session.json").write_text(json.dumps(sess, indent=1))
    return sess


def session_env(sess, extra=None):
    env = {k: os.environ[k] for k in KEEP_ENV if k in os.environ}
    env.update(DRGNX_UI_NAME=sess["name"], DRGNX_UI_RUN=sess["run"], DRGNX_UI_HARNESS=str(HARNESS),
               DRGNX_UI_CONFIG=sess["config_dir"], EMACS_SOCKET_NAME=sess["socket"])
    env.update(extra or {})
    return env


def env_argv(env):
    return ["env", "-i", *[f"{k}={v}" for k, v in sorted(env.items())]]


def compositor_argv(sess):
    return ["dbus-run-session", "--", "mutter", "--headless", "--wayland", "--no-x11",
            "--wayland-display", sess["name"], "--virtual-monitor", sess["size"], "--",
            emacs_bin(), "--init-directory", str(Path(sess["run"]) / "init"), "--fullscreen"]


def el(v):
    """A Python value as an elisp literal (JSON string syntax reads as an elisp string)."""
    if v is None or v is False:
        return "nil"
    if v is True:
        return "t"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(str(v), ensure_ascii=False)


def parse_reply(stdout):
    """emacsclient prints the API's JSON text as an elisp string literal."""
    return json.loads(json.loads(stdout.strip(), strict=False), strict=False)


def launch_argv(sess):
    return ["systemd-run", "--user", "--quiet", "--collect", "--unit", sess["name"],
            "-p", "RuntimeMaxSec=1800", "-p", "MemoryMax=3G",
            "--", *env_argv(session_env(sess)), *compositor_argv(sess)]


def unit_active(name):
    return subprocess.run(["systemctl", "--user", "is-active", "--quiet", name]).returncode == 0


def next_name(root):
    n = 1
    while (Path(root) / f"drgnx-ui-{n}").exists() or unit_active(f"drgnx-ui-{n}"):
        n += 1
    return f"drgnx-ui-{n}"


def journal_tail(name, lines=30):
    return subprocess.run(["journalctl", "--user", "-u", name, "-n", str(lines), "--no-pager", "-o", "cat"],
                          capture_output=True, text=True).stdout


def start(config=None, size="1600x900", timeout=60):
    root = state_root()
    root.mkdir(parents=True, exist_ok=True)
    sess = prepare_run(next_name(root), config, size, root)
    p = subprocess.run(launch_argv(sess), capture_output=True, text=True)
    if p.returncode:
        shutil.rmtree(sess["run"])
        raise HarnessError(f"systemd-run failed: {p.stderr.strip()}")
    ready, end = Path(sess["run"]) / "ready.json", time.time() + timeout
    while not ready.is_file():
        if time.time() > end or not unit_active(sess["name"]):
            log = journal_tail(sess["name"])
            stop(sess["name"])
            raise HarnessError(f"{sess['name']} did not become ready:\n{log}")
        time.sleep(0.1)
    sess["ready"] = json.loads(ready.read_text())
    (Path(sess["run"]) / "session.json").write_text(json.dumps(sess, indent=1))
    return sess


def stop(name):
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise Refused(f"refused: {name!r} is not a drgnx harness session (drgnx-ui-N)")
    subprocess.run(["systemctl", "--user", "stop", name], capture_output=True)
    run = state_root() / name
    if run.is_dir():
        shutil.rmtree(run)
    return {"stopped": name}


def ls():
    root = state_root()
    out = []
    for d in sorted(root.iterdir()) if root.is_dir() else []:
        if NAME_RE.fullmatch(d.name) and (d / "session.json").is_file():
            s = json.loads((d / "session.json").read_text())
            out.append({"name": d.name, "active": unit_active(d.name), "config": s["config"], "size": s["size"]})
    return out


def unit_cmdline(name):
    return subprocess.run(["systemctl", "--user", "show", "-p", "ExecStart", "--value", name],
                          capture_output=True, text=True).stdout


def reap_targets(root, units, cmdline=unit_cmdline):
    """Sessions of this state ROOT: run dirs in it, plus live units whose command line points into it.
    Units of other state roots (another checkout, a test run) are left alone."""
    names = {d.name for d in root.iterdir()} if root.is_dir() else set()
    for line in units.splitlines():
        if line.strip():
            name = line.split()[0].removesuffix(".service")
            if NAME_RE.fullmatch(name) and f"DRGNX_UI_RUN={root}/{name}" in (cmdline(name) or ""):
                names.add(name)
    return sorted(n for n in names if NAME_RE.fullmatch(n))


def reap():
    """Stop every session of this state root, live or stale, and remove its run directory."""
    units = subprocess.run(["systemctl", "--user", "list-units", "drgnx-ui-*", "--all", "--plain",
                            "--no-legend"], capture_output=True, text=True).stdout
    names = reap_targets(state_root(), units)
    for n in names:
        stop(n)
    return names


def own_session(name):
    """The session NAME if this harness started it and its socket exists; else Refused."""
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise Refused(f"refused: {name!r} is not a drgnx harness session (drgnx-ui-N)")
    run = state_root() / name
    f = run / "session.json"
    if not f.is_file():
        raise Refused(f"refused: no harness session {name} (see ui_list)")
    sess = json.loads(f.read_text())
    sock = run / "sock" / name
    if sess.get("socket") != str(sock) or not sock.is_socket():
        raise Refused(f"refused: {name} has no live socket (stopped or crashed? see ui_list)")
    return sess


def call(sess, form, timeout=20):
    p = subprocess.run(["timeout", str(timeout), "emacsclient", "-s", sess["socket"], "-e", form],
                       capture_output=True, text=True)
    if p.returncode == 124:
        raise HarnessError(f"{sess.get('name')}: no answer in {timeout}s "
                           "(stuck on a prompt? take a ui_screenshot)")
    if p.returncode:
        raise HarnessError((p.stderr or p.stdout).strip())
    return parse_reply(p.stdout)


def act(sess, a):
    """Queue one action (see docs/harness.md); returns the API's reply."""
    opts = f"{el(a.get('button'))} {el(a.get('count'))} {el(a.get('hold_ms'))}"
    if "keys" in a:
        return call(sess, f"(drgnx-uitest-api-keys {el(a['keys'])})")
    if "type" in a:
        return call(sess, f"(drgnx-uitest-api-type {el(a['type'])})")
    if "buffer" in a and "text" in a:
        return call(sess, f"(drgnx-uitest-api-click-target {el(a['buffer'])} {el(a['text'])} {opts})")
    if "x" in a and "y" in a:
        return call(sess, f"(drgnx-uitest-api-click {int(a['x'])} {int(a['y'])} {opts})")
    raise HarnessError(f"unknown action {a!r}: use keys, type, buffer+text or x+y")


def wait(sess, quiet_ms=300, timeout_s=10):
    end = time.time() + timeout_s
    while time.time() < end:
        if call(sess, f"(drgnx-uitest-api-status {int(quiet_ms)})")["settled"]:
            return True
        time.sleep(0.05)
    return False


def measure(sess, actions, quiet_ms=300, timeout_s=10):
    call(sess, "(drgnx-uitest-api-measure-begin)")
    replies = [act(sess, a) for a in actions]
    settled = wait(sess, quiet_ms, timeout_s)
    report = call(sess, "(drgnx-uitest-api-measure-end)")
    report.update(settled=settled, actions=replies)
    return report


def state(sess):
    return call(sess, "(drgnx-uitest-api-state)")


def composite_argv(cap, out):
    argv = ["magick", cap["root"]]
    for c in cap["children"]:
        argv += [c["path"], "-geometry", f"+{c['x']}+{c['y']}", "-composite"]
    return argv + [str(out)]


def screenshot(sess, path=None):
    """PNG of the root frame with child frames composited. Returns path, size, window map."""
    tmp = tempfile.mkdtemp(dir=Path(sess["run"]) / "out")
    cap = call(sess, f"(drgnx-uitest-api-screenshot {el(tmp)})")
    if path:
        out = Path(path)
    else:
        shots = state_root() / "shots"
        shots.mkdir(parents=True, exist_ok=True)
        out = shots / f"{sess['name']}-{time.strftime('%Y%m%d-%H%M%S')}.png"
    subprocess.run(composite_argv(cap, out), check=True, capture_output=True)
    shutil.rmtree(tmp)
    return {"path": str(out), "width": cap["width"], "height": cap["height"],
            "children": len(cap["children"]), "windows": cap["windows"]}


def run_ert_session(tests_dir, timeout=110):
    """Run the ERT suite in TESTS_DIR inside a foreground session. Returns (rc, results, run)."""
    name = f"drgnx-ui-test-{os.getpid()}-{int(time.time() * 1000) % 100000}"
    sess = prepare_run(name, None, "1600x900")
    run = Path(sess["run"])
    results = run / "results.json"
    env = session_env(sess, {"DRGNX_UI_TEST": str(Path(tests_dir).resolve()), "DRGNX_UI_RESULTS": str(results)})
    with open(run / "session.log", "w") as log:
        p = subprocess.Popen([*env_argv(env), *compositor_argv(sess)], stdout=log,
                             stderr=subprocess.STDOUT, start_new_session=True)
        try:
            rc = p.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)
            p.wait()
            rc = 124
    subprocess.run(["pkill", "-KILL", "-f", name], capture_output=True)  # belt and braces
    data = json.loads(results.read_text()) if results.is_file() else None
    return rc, data, run


def run_ui_tests():
    """`drgnx test --ui`: GUI ERT suite in a session, then live session tests. Returns exit code."""
    t0 = time.time()
    timeout = int(os.environ.get("DRGNX_UI_TEST_TIMEOUT", "110"))
    rc, results, run = run_ert_session(REPO / "test" / "ui", timeout)
    if results:
        print(f"ui ERT: {results['passed']}/{results['total']} passed")
        for f in results["failures"]:
            print(f"  FAIL {f['name']}: {f['condition']}")
    else:
        print(f"ui ERT: no results (exit {rc}); log kept in {run}")
    ok = rc == 0 and results is not None and results["failed"] == 0
    if ok:
        shutil.rmtree(run)
    live = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", str(REPO / "test" / "ui"),
                           "-p", "test_*.py"], env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})
    ok = ok and live.returncode == 0
    print(f"ui tier: {'green' if ok else 'RED'} in {time.time() - t0:.1f}s")
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(prog="drgnx ui", description="Headless GUI Emacs sessions for tests and agents.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("start")
    p.add_argument("--config", default="minimal")
    p.add_argument("--size", default="1600x900")
    for c in ("stop", "state"):
        sub.add_parser(c).add_argument("name")
    sub.add_parser("ls")
    sub.add_parser("reap")
    sub.add_parser("test-ui")
    p = sub.add_parser("shot")
    p.add_argument("name")
    p.add_argument("path", nargs="?")
    p = sub.add_parser("click")
    p.add_argument("name")
    p.add_argument("xy", nargs="*", type=int)
    p.add_argument("--buffer")
    p.add_argument("--text")
    p.add_argument("--button", type=int)
    p.add_argument("--count", type=int)
    p.add_argument("--hold-ms", type=int)
    p = sub.add_parser("keys")
    p.add_argument("name")
    p.add_argument("keys")
    p = sub.add_parser("type")
    p.add_argument("name")
    p.add_argument("text")
    p = sub.add_parser("measure")
    p.add_argument("name")
    p.add_argument("actions", help="JSON list of actions")
    a = ap.parse_args(argv)
    if a.cmd == "test-ui":
        return run_ui_tests()
    try:
        if a.cmd == "start":
            out = start(a.config, a.size)
        elif a.cmd == "stop":
            out = stop(a.name)
        elif a.cmd == "ls":
            out = ls()
        elif a.cmd == "reap":
            out = reap()
        elif a.cmd == "state":
            out = state(own_session(a.name))
        elif a.cmd == "shot":
            out = screenshot(own_session(a.name), a.path)
        elif a.cmd == "click":
            action = {"buffer": a.buffer, "text": a.text} if a.buffer else dict(zip(("x", "y"), a.xy))
            action.update({k: v for k, v in (("button", a.button), ("count", a.count), ("hold_ms", a.hold_ms)) if v})
            out = measure(own_session(a.name), [action])
        elif a.cmd == "keys":
            out = measure(own_session(a.name), [{"keys": a.keys}])
        elif a.cmd == "type":
            out = measure(own_session(a.name), [{"type": a.text}])
        elif a.cmd == "measure":
            out = measure(own_session(a.name), json.loads(a.actions))
    except HarnessError as e:
        print(f"drgnx ui: {e}", file=sys.stderr)
        return 1
    print(json.dumps(out, indent=1, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
